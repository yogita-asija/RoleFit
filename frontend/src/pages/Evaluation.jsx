import { useEffect, useState } from 'react';
import { Play, FlaskConical, BadgeCheck } from 'lucide-react';
import { getEvaluation, getPrompts, startEvaluation, errMsg } from '../services/api.js';
import { Spinner } from '../components/ui.jsx';

const CRIT = [['relevance', 'Relevance'], ['accuracy', 'Accuracy'], ['grounding', 'Evidence grounding'], ['completeness', 'Completeness'], ['reliability', 'Reliability / hallucination prevention'], ['overall', 'Overall']];
const COLORS = { v1: '#9A95C9', v2: '#2F6FED', v3: '#5B4BDB' };

function Chart({ summary }) {
  return (
    <div className="space-y-4" role="img" aria-label="Grouped bar chart of criterion scores out of 5 for each prompt version">
      {CRIT.slice(0, 5).map(([k, label]) => (
        <div key={k}><p className="mb-1 text-sm font-semibold">{label}</p>
          {['v1', 'v2', 'v3'].map((v) => (<div key={v} className="mb-1 flex items-center gap-2 text-xs">
            <span className="w-6 text-mute">{v.toUpperCase()}</span>
            <div className="h-4 flex-1 rounded bg-violet-soft"><div className="h-4 rounded" style={{ width: `${((summary[v][k] || 0) / 5) * 100}%`, background: COLORS[v] }} /></div>
            <span className="w-8 text-right font-semibold">{summary[v][k] ?? '-'}</span></div>))}
        </div>))}
    </div>
  );
}

export default function Evaluation({ health, notify }) {
  const [prompts, setPrompts] = useState([]); const [ev, setEv] = useState(null); const [job, setJob] = useState(null); const [open, setOpen] = useState('v3');
  const load = () => getEvaluation().then((d) => { setEv(d); setJob(d.job); return d; }).catch((e) => notify('error', errMsg(e)));
  useEffect(() => { getPrompts().then(setPrompts).catch(() => {}); load(); }, []);
  useEffect(() => { if (job?.status !== 'running') return; const t = setInterval(load, 4000); return () => clearInterval(t); }, [job?.status]);
  const run = async () => { try { setJob(await startEvaluation()); notify('success', 'Evaluation started. 15 AI calls will take a few minutes.'); } catch (e) { notify('error', errMsg(e)); } };
  const e = ev?.evaluation; const real = e?.mode === 'real'; const running = job?.status === 'running';

  return (
    <main className="mx-auto max-w-6xl px-4 py-8">
      <h1 className="text-3xl font-bold">Prompt evaluation</h1>
      <p className="mt-1 max-w-3xl text-mute">Three prompt versions run on the same five fictional test cases. Each output is scored from 1 to 5 on five criteria by automatic checks against known expected skills and gaps.</p>

      {e && (real
        ? <div className="mt-4 flex gap-2 rounded-xl border border-mint bg-mint-soft p-4 text-sm text-mint"><BadgeCheck size={18} /><p><b>Real results.</b> Generated by {e.provider} ({e.model}) on {new Date(e.generatedAt).toLocaleString()}.</p></div>
        : <div className="mt-4 flex gap-2 rounded-xl border border-amber bg-amber-soft p-4 text-sm text-amber"><FlaskConical size={18} className="shrink-0" /><p><b>Illustrative data, not experiment results.</b> {e.note}</p></div>)}

      <div className="mt-4 flex flex-wrap items-center gap-3">
        <button className="btn-primary" onClick={run} disabled={running || health?.config?.demoMode}>{running ? <Spinner label={`Running ${job.progress.done}/${job.progress.total}`} /> : <><Play size={16} />Run real evaluation</>}</button>
        {health?.config?.demoMode && <span className="text-sm text-mute">Needs a Gemini or OpenAI key on the server. Or run <code>npm run evaluate</code> in the backend folder.</span>}
        {job?.status === 'error' && <span role="alert" className="text-sm text-rose">Evaluation failed: {job.error}</span>}
      </div>

      {e && (
        <div className="mt-6 grid gap-5 lg:grid-cols-2">
          <section className="card overflow-x-auto p-5"><h2 className="mb-3 text-xl font-semibold">Comparison table (out of 5)</h2>
            <table className="w-full text-left text-sm"><thead className="text-mute"><tr><th className="py-1">Criterion</th><th>V1</th><th>V2</th><th>V3</th></tr></thead>
              <tbody>{CRIT.map(([k, l]) => (<tr key={k} className={`border-t border-line ${k === 'overall' ? 'font-bold' : ''}`}><td className="py-2 pr-2">{l}</td>{['v1', 'v2', 'v3'].map((v) => <td key={v}>{e.summary[v][k] ?? '-'}</td>)}</tr>))}</tbody></table></section>
          <section className="card p-5"><h2 className="mb-3 text-xl font-semibold">Chart</h2><Chart summary={e.summary} /></section>
        </div>)}

      {real && (
        <section className="card mt-5 overflow-x-auto p-5"><h2 className="mb-3 text-xl font-semibold">Per test case</h2>
          <table className="w-full text-left text-sm"><thead className="text-mute"><tr><th className="py-1">Case</th><th>Version</th><th>Match score</th><th>Overall</th><th>False claims</th><th>Downgraded</th></tr></thead>
            <tbody>{e.runs.map((r, i) => (<tr key={i} className="border-t border-line"><td className="py-2">{r.caseId} {ev.cases.find((c) => c.id === r.caseId)?.title}</td><td>{r.version.toUpperCase()}</td>
              {r.metrics ? <><td>{r.result.score.total}</td><td>{(['relevance', 'accuracy', 'grounding', 'completeness', 'reliability'].reduce((s, c) => s + r.metrics[c], 0) / 5).toFixed(2)}</td><td>{r.metrics.details.falseClaims}</td><td>{r.metrics.details.downgraded}</td></> : <td colSpan={4} className="text-rose">Failed: {r.error}</td>}</tr>))}</tbody></table></section>)}

      <section className="mt-8"><h2 className="text-xl font-semibold">The three prompts</h2>
        <div className="mt-3 space-y-3">{prompts.map((p) => (
          <div key={p.id} className="card p-4"><button className="w-full text-left" onClick={() => setOpen(open === p.id ? null : p.id)} aria-expanded={open === p.id}><b>{p.name}</b><span className="block text-sm text-mute">{p.summary}</span></button>
            {open === p.id && <pre className="mt-3 max-h-96 overflow-auto whitespace-pre-wrap rounded-xl bg-violet-soft p-4 text-xs">{p.system}</pre>}</div>))}</div></section>

      <section className="card mt-8 p-5"><h2 className="text-xl font-semibold">Why prompt engineering improves reliability</h2>
        <ul className="mt-2 list-disc space-y-1 pl-5 text-sm text-mute">
          <li><b>V1 to V2:</b> splitting the job into individual requirements and fixing the JSON shape makes outputs complete, comparable and scoreable by a defined rubric instead of a guess.</li>
          <li><b>V2 to V3:</b> requiring a verbatim quote for every claim, plus code that checks each quote against the resume, turns "trust the model" into "verify the model". Unverifiable claims are downgraded and unsafe rewritten bullets are removed.</li>
          <li><b>Limits:</b> the metrics are automatic checks on five small fictional cases. They show a trend, not statistical proof. Review the raw outputs yourself.</li>
        </ul></section>
    </main>
  );
}
